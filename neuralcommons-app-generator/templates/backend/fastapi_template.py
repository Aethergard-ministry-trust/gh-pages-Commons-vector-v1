class InstrumentIn(BaseModel):
    payload: dict = Field(default_factory=dict)
    trust: str = NAMESPACE
    previous: str = "000"


class GenerateIn(BaseModel):
    prompt: str
    model: str = MODEL


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "namespace": NAMESPACE, "model": MODEL, "instruments": len(read_ledger())}


@app.get("/dictionary")
def dictionary() -> dict:
    return DICTIONARY


@app.get("/instruments")
def list_instruments(trust: str | None = None, q: str | None = None) -> dict:
    rows = list(reversed(read_ledger()))
    if trust:
        rows = [row for row in rows if row.get("trust") == trust]
    if q:
        needle = q.lower()
        rows = [row for row in rows if needle in json.dumps(row.get("payload", {})).lower()]
    return {"count": len(rows), "instruments": rows}


@app.post("/instruments", status_code=201)
def create_instrument(body: InstrumentIn) -> dict:
    rows = read_ledger()
    key = load_or_create_key()
    record = {
        "instrument": f"{len(rows) + 1:03d}",
        "trust": body.trust,
        "dictionary": DICTIONARY["name"],
        "previous": body.previous if body.previous else (rows[-1]["cid"] if rows else "000"),
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "payload": body.payload,
        "public_key": public_key_b64(key),
    }
    record["cid"] = content_cid(record)
    record["signature"] = base64.b64encode(key.sign(canonical_json(record))).decode("ascii")
    append_ledger(record)
    return record


@app.get("/instruments/{cid}")
def get_instrument(cid: str) -> dict:
    instrument = find(cid)
    if instrument is None:
        raise HTTPException(status_code=404, detail={"error": f"unknown cid {cid}"})
    return instrument


@app.post("/verify/{cid}")
def verify_instrument(cid: str) -> dict:
    instrument = find(cid)
    if instrument is None:
        raise HTTPException(status_code=404, detail={"error": f"unknown cid {cid}"})
    ok, reason = verify(instrument)
    return {"cid": cid, "verified": ok, "reason": reason}


@app.get("/provenance/{cid}")
def provenance(cid: str) -> dict:
    chain: list[dict] = []
    current = find(cid)
    if current is None:
        raise HTTPException(status_code=404, detail={"error": f"unknown cid {cid}"})
    while current is not None and len(chain) < 1000:
        chain.append(current)
        current = find(current.get("previous", "000")) if current.get("previous") != "000" else None
    chain.reverse()
    return {"cid": cid, "length": len(chain), "chain": chain}


@app.post("/ollama/generate")
def ollama_generate(body: GenerateIn) -> dict:
    """Proxy one generation call to the local model and record it in the chain."""
    import httpx

    try:
        response = httpx.post(
            f"{OLLAMA_URL}/api/generate",
            json={"model": body.model, "prompt": body.prompt, "stream": False},
            timeout=120.0,
        )
        response.raise_for_status()
        answer = response.json().get("response", "")
        state = "answered"
    except Exception as exc:  # noqa: BLE001 - report the failure, never invent an answer
        answer = None
        state = f"unavailable: {type(exc).__name__}"
    record = create_instrument(
        InstrumentIn(payload={"model": body.model, "prompt_sha256": hashlib.sha256(body.prompt.encode()).hexdigest(), "state": state}, previous="")
    )
    return {"state": state, "response": answer, "instrument": record}
