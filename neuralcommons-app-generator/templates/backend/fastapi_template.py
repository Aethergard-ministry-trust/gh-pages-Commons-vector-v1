# --- canonical form and content addressing ---------------------------------


def canonical_json(obj: Any) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def content_cid(obj: Any) -> str:
    digest = hashlib.sha256(canonical_json(obj)).digest()
    encoded = base64.b32encode(digest).decode("ascii").lower().rstrip("=")
    return "b" + encoded


# --- key material and ledger ------------------------------------------------


def load_or_create_key() -> Ed25519PrivateKey:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if KEY_FILE.exists():
        return serialization.load_pem_private_key(KEY_FILE.read_bytes(), password=None)
    key = Ed25519PrivateKey.generate()
    KEY_FILE.write_bytes(
        key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    KEY_FILE.chmod(0o600)
    return key


def public_key_b64(key: Ed25519PrivateKey) -> str:
    raw = key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
    )
    return base64.b64encode(raw).decode("ascii")


def read_ledger() -> list[dict]:
    if not LEDGER.exists():
        return []
    return json.loads(LEDGER.read_text("utf-8"))


def append_ledger(instrument: dict) -> None:
    rows = read_ledger()
    rows.append(instrument)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n", "utf-8")


def find(cid: str) -> dict | None:
    return next((row for row in read_ledger() if row["cid"] == cid), None)


def verify(instrument: dict) -> tuple[bool, str]:
    """Recompute the hash and the signature of a stored instrument."""
    body = {key: value for key, value in instrument.items() if key not in {"cid", "signature"}}
    try:
        public_key = instrument["public_key"]
    except KeyError:
        return False, "instrument has no public_key"
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

    key = Ed25519PublicKey.from_public_bytes(base64.b64decode(public_key))
    try:
        key.verify(base64.b64decode(instrument["signature"]), canonical_json(body))
    except Exception:  # noqa: BLE001 - any verification error means "unverified"
        return False, "signature does not match canonical bytes"
    if content_cid(body) != instrument["cid"]:
        return False, "cid does not match canonical bytes"
    return True, "verified"


